"""
Аналитический вывод для матриц 2x2 с элементами ±1.

Матрица:
    A = [[A, B],
         [C, D]]
с A, B, C, D ∈ {-1, +1}, равновероятно, независимо.

После симметризации B = (A + A^T)/sqrt(2):
    B = [[a, b],
         [b, c]],
где a = 2A/sqrt(2) = A*sqrt(2),  c = D*sqrt(2),
    b = (B + C)/sqrt(2).

Собственные числа:
    lambda_{1,2} = (a + c)/2 ± sqrt(((c - a)/2)^2 + b^2)

Разность:
    s = 2*sqrt(d^2 + b^2),  d = (c - a)/2

d = (D - A)*sqrt(2)/2 = (D - A)/sqrt(2)
b = (B + C)/sqrt(2)

(D - A) ∈ {-2, 0, 2}   с вероятностями  1/4, 1/2, 1/4
(B + C) ∈ {-2, 0, 2}   с вероятностями  1/4, 1/2, 1/4

Значит d ∈ {-sqrt(2), 0, +sqrt(2)} с вероятностями 1/4, 1/2, 1/4,
      b ∈ {-sqrt(2), 0, +sqrt(2)} с вероятностями 1/4, 1/2, 1/4.

Возможные значения s = 2*sqrt(d^2 + b^2):

    d^2 ∈ {0, 2},  b^2 ∈ {0, 2}

    s = 0      ->  d=0, b=0
    s = 2*sqrt(2)  ->  ровно одно из (d^2, b^2) = 2, другое = 0
    s = 4      ->  d^2 = b^2 = 2

Вероятности (d и b независимы):
    P(d=0) = 1/2,   P(d^2=2) = 1/2
    P(b=0) = 1/2,   P(b^2=2) = 1/2

    P(s=0)         = 1/2 * 1/2 = 1/4
    P(s=2*sqrt(2)) = 2 * (1/2 * 1/2) = 1/2
    P(s=4)         = 1/2 * 1/2 = 1/4

Среднее:
    <s> = 0*(1/4) + 2*sqrt(2)*(1/2) + 4*(1/4)
        = sqrt(2) + 1 ≈ 2.4142

После нормировки s -> s / <s> среднее становится 1.

Итоговое распределение — дискретное, три точки:
    s' = 0       с вероятностью 1/4
    s' = 2*sqrt(2)/(1+sqrt(2)) ≈ 1.1716   с вероятностью 1/2
    s' = 4/(1+sqrt(2))         ≈ 1.6569   с вероятностью 1/4

Это НЕ распределение Вигнера (15). Совпадения с ним нет и быть
не должно: при n=2 дискретность элементов ±1 слишком груба.
"""

import numpy as np


def analytic_bernoulli_2x2():
    values = np.array([0.0, 2.0 * np.sqrt(2.0), 4.0])
    probs = np.array([0.25, 0.5, 0.25])

    mean = float(np.sum(values * probs))
    values_norm = values / mean

    print("аналитика для 2x2, ±1:")
    print("  значения s:", values)
    print("  вероятности:", probs)
    print("  <s> =", mean)
    print("  нормированные значения s':", values_norm)
    return values_norm, probs


if __name__ == "__main__":
    analytic_bernoulli_2x2()